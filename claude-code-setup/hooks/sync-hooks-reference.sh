#!/usr/bin/env bash
# sync-hooks-reference.sh — Extracts hooks from live settings.json into setup-repo reference file
# Runs at SessionEnd (async). Keeps hooks-macos.json always in sync with live settings.
# Created: 2026-03-25 by Intelligenz-Vorschlag #715

set +e  # Hooks muessen IMMER weiterlaufen, nie bei Fehler abbrechen

SETTINGS="$HOME/.claude/settings.json"
SETUP_DIR="$HOME/proggs/claude-code-setup"
REF_FILE="$SETUP_DIR/hooks-macos.json"
COMMENT="Complete hooks reference for macOS. Merge into ~/.claude/settings.json on macOS. Uses bash for command hooks. Prompt-injection-defender requires Python 3 (python3). Parry requires ~/.cargo/bin/parry. Bun at /opt/homebrew/bin/bun. AUTO-GENERATED by sync-hooks-reference.sh — do not edit manually."

# Bail if settings or setup dir missing
[[ -f "$SETTINGS" ]] || exit 0
[[ -d "$SETUP_DIR" ]] || exit 0

# Bewusst stillgelegte Referenz respektieren (Direktive #3: nichts ueberschreiben, was jemand
# absichtlich geleert hat). Traegt die vorhandene Datei den Marker "intentionally removed" oder
# "sync": false, laesst der Hook sie in Ruhe. Ohne diese Bremse schrieb er die Datei bei JEDEM
# SessionEnd neu, waehrend der committete Stand leer bleiben sollte -- ein Konflikt, der bei jedem
# git status wieder auftauchte. Wieder einschalten: Marker aus dem _comment entfernen.
if [[ -f "$REF_FILE" ]]; then
    STILLGELEGT=$(python3 -c "
import json, sys
try:
    d = json.load(open('$REF_FILE'))
except Exception:
    print('0'); sys.exit()
marker = 'intentionally removed' in str(d.get('_comment', ''))
print('1' if marker or d.get('sync') is False else '0')
" 2>/dev/null || echo "0")
    [[ "$STILLGELEGT" == "1" ]] && exit 0
fi

# Extract hooks section with python3
TMP_FILE="$REF_FILE.tmp.$$"
# Poka-Yoke (Direktive #3, Stufe 3): trap raeumt die Temp-Datei bei JEDEM Exit
# (normal, Fehler, Signal/Timeout am SessionEnd) auf — verhindert verwaiste .tmp-Leichen.
# Nach erfolgreichem mv existiert TMP_FILE nicht mehr; das rm ist dann harmlos.
trap 'rm -f "$TMP_FILE" 2>/dev/null' EXIT
python3 -c "
import json, sys, os

settings_path = os.path.expanduser('$SETTINGS')
with open(settings_path) as f:
    settings = json.load(f)

hooks = settings.get('hooks', {})
if not hooks:
    sys.exit(0)

output = {
    '_comment': '''$COMMENT''',
    'hooks': hooks
}
print(json.dumps(output, indent='\t', ensure_ascii=False))
" > "$TMP_FILE" 2>/dev/null || { rm -f "$TMP_FILE"; exit 0; }

# Only update if content actually differs (ignore whitespace)
if [[ -f "$REF_FILE" ]]; then
    # Compare JSON structure, not formatting
    # sha256 statt hash(): Pythons String-hash() ist pro Prozess randomisiert (PYTHONHASHSEED),
    # daher waren OLD_HASH/NEW_HASH fast immer ungleich -> Datei wurde bei JEDEM SessionEnd
    # unnoetig neu geschrieben (Git-Churn). sha256 ist deterministisch ueber Prozesse hinweg.
    OLD_HASH=$(python3 -c "import json,hashlib; print(hashlib.sha256(json.dumps(json.load(open('$REF_FILE')).get('hooks',{}), sort_keys=True).encode()).hexdigest())" 2>/dev/null || echo "none")
    NEW_HASH=$(python3 -c "import json,hashlib; print(hashlib.sha256(json.dumps(json.load(open('$TMP_FILE')).get('hooks',{}), sort_keys=True).encode()).hexdigest())" 2>/dev/null || echo "changed")
    if [[ "$OLD_HASH" == "$NEW_HASH" ]]; then
        rm -f "$TMP_FILE"
        exit 0
    fi
fi

mv "$TMP_FILE" "$REF_FILE"
echo "Hooks-Referenz aktualisiert: hooks-macos.json"
