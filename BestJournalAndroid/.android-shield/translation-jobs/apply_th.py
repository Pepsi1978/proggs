def normalize_quotes(value):
    # The existing file uses NO escaped/raw double-quotes inside strings.
    # Our STR literals contain backslash-quote (\") and German typographic
    # quotes („ ").  Convert all of these to Thai angle quotation marks
    # 「 ... 」 which need no XML escaping and read naturally in Thai UI.
    # Pair them up across each value.
    # 1) German opening/closing typographic quotes.
    value = value.replace('„', '「').replace('“', '」')  # „ -> 「 , " -> 」
    value = value.replace('”', '」')  # ” -> 」 (safety)
    # 2) Escaped straight double-quotes \" : alternate open/close.
    out = []
    open_next = True
    i = 0
    while i < len(value):
        if value[i] == '\\' and i + 1 < len(value) and value[i + 1] == '"':
            out.append('「' if open_next else '」')
            open_next = not open_next
            i += 2
            continue
        if value[i] == '"':  # any stray raw quote
            out.append('「' if open_next else '」')
            open_next = not open_next
            i += 1
            continue
        out.append(value[i])
        i += 1
    return ''.join(out)


def build_string_elem(key, value):
    value = normalize_quotes(value)
    # value contains literal \n as backslash-n; no double-quotes remain.
    return '    <string name="%s">%s</string>' % (key, value)

def build_plural_elem(key, mapping):
    lines = ['    <plurals name="%s">' % key]
    for q, txt in mapping.items():
        lines.append('        <item quantity="%s">%s</item>' % (q, txt))
    lines.append('    </plurals>')
    return "\n".join(lines)

